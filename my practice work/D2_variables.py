import keyword

# -----------------------------------
# 1. Keywords
# -----------------------------------
print("===== Python Keywords =====")
print(keyword.kwlist)

# -----------------------------------
# 2. Identifiers (variable names)
# -----------------------------------
print("\n===== Identifiers Example =====")
name = "Simran"     # valid identifier
_age = 25           # starts with underscore
totalAmount = 500   # camelCase style

print("name =", name)
print("_age =", _age)
print("totalAmount =", totalAmount)

# -----------------------------------
# 3. Variables (storing different types of data)
# -----------------------------------
print("\n===== Variables Example =====")
x = 10              # integer
y = 3.14            # float
language = "Python" # string

print("x =", x)
print("y =", y)
print("language =", language)
