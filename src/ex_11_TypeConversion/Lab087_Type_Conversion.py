# -------------------------------------------------------------
# Step 1: Type Conversion Example (String → Integer)
# -------------------------------------------------------------
a = "10"
print(type(a))     # Before conversion → <class 'str'>

a = int(a)         # Convert string to integer
print(type(a))     # After conversion → <class 'int'>


# -------------------------------------------------------------
# Common Python Type Conversion Functions
# -------------------------------------------------------------
# int()    → Convert to integer
# str()    → Convert to string
# float()  → Convert to float
# bool()   → Convert to boolean
# list()   → Convert to list
# tuple()  → Convert to tuple
# set()    → Convert to set
# dict()   → Convert to dictionary (special cases only)
# complex()→ Convert to complex number
