# -------------------------------------------------------------
# Step 1: Function with Parameters AND Return Value
# -------------------------------------------------------------
# This function accepts two numbers (a, b) and returns their sum.

def sum_of_two(a, b):
    return a + b


# -------------------------------------------------------------
# Step 2: Calling the Function and Capturing the Result
# -------------------------------------------------------------
result = sum_of_two(4, 5)
print(result)      # Output: 9
