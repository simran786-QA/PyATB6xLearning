import csv

# -------------------------------------------------------------
# Step 1: Open CSV file
# -------------------------------------------------------------
# Default mode = read ('r')

with open('TD.csv') as csvfile:

    # ---------------------------------------------------------
    # Step 2: Create CSV reader object
    # ---------------------------------------------------------
    reader = csv.reader(csvfile)

    # ---------------------------------------------------------
    # Step 3: Iterate through rows
    # ---------------------------------------------------------
    for col in reader:

        # -----------------------------------------------------
        # Step 4: Print specific columns
        # -----------------------------------------------------
        print(col[0], col[1], sep="|")