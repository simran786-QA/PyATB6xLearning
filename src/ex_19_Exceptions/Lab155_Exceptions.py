# Step 1: Create a variable (currently commented)
# a = 10

# Step 2: Try printing the variable
# Because 'a' is commented, it doesn't exist
# -------------------------------------------------------------
# print(a)   # ❌ NameError: name 'a' is not defined


# -------------------------------------------------------------
# Hindi Explanation:
# - Variable 'a' comment kiya hua hai, isliye Python ko 'a' ka koi
#   value nahi mila.
# - Jab print(a) call kiya, Python ne error diya:
#   NameError: name 'a' is not defined.
#
# English Explanation:
# - The variable 'a' is commented out, so Python never creates it.
# - When print(a) runs, Python throws:
#   NameError: name 'a' is not defined.
# -------------------------------------------------------------


# -------------------------------------------------------------
# Summary:
# 1. NameError tab aata hai jab variable defined nahi hota.
# 2. Variable ko define ya uncomment karna hota hai.
# 3. Python line-by-line execute karta hai, undefined variable → error.
