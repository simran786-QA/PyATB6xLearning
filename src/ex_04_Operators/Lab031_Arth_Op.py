# Step 1: Basic Arithmetic Operations
print("📘 Basic Arithmetic Operations\n")

print("Addition (2 + 2) =", 2 + 2)
print("Subtraction (2 - 2) =", 2 - 2)
print("Multiplication (2 * 2) =", 2 * 2)
print("Division (2 / 2) =", 2 / 2)

# -------------------------------------------------------------
# Step 2: More Examples (to understand integer vs float results)
print("\n📗 More Examples\n")

a = 15
b = 4

print(f"Numbers: a = {a}, b = {b}")
print(f"Addition: a + b = {a + b}")
print(f"Subtraction: a - b = {a - b}")
print(f"Multiplication: a * b = {a * b}")
print(f"Division (Float): a / b = {a / b:.2f}")  # float division
print(f"Floor Division (Integer only): a // b = {a // b}")
print(f"Modulus (Remainder): a % b = {a % b}")
print(f"Exponentiation (Power): a ** b = {a ** b}")

