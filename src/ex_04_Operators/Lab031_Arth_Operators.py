# 🎯 Objective:
# Understand how Python performs different arithmetic operations.
# Operators covered: +, -, *, /, //, %, **

# -------------------------------------------------------------
# Step 1: Assign values
a, b = 10, 3

print(f"Given values: a = {a}, b = {b}\n")

# -------------------------------------------------------------
# Step 2: Arithmetic Operations
print("📘 Arithmetic Operations and Results:\n")

# Addition (जोड़)
print(f"Addition (a + b)         → {a + b}")  # 10 + 3 = 13

# Subtraction (घटाना)
print(f"Subtraction (a - b)      → {a - b}")  # 10 - 3 = 7

# Multiplication (गुणा)
print(f"Multiplication (a * b)   → {a * b}")  # 10 * 3 = 30

# Division (भाग) - gives float result
print(f"Division (a / b)         → {a / b}")  # 10 / 3 = 3.3333...

# Floor Division (पूर्णांक भाग)
print(f"Floor Division (a // b)  → {a // b}") # 10 // 3 = 3

# Modulus (शेषफल)
print(f"Modulus (a % b)          → {a % b}")  # 10 % 3 = 1

# Exponentiation (घातांक)
print(f"Exponentiation (a ** b)  → {a ** b}") # 10 ** 3 = 1000

