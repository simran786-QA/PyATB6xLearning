# Equal to (==)
print(2 == 2)  # ✅ True, both values are same
print(2 == 3)  # ❌ False, values are not equal

# Not equal (!=)
print(5 != 3)  # ✅ True, 5 is not equal to 3
print(5 != 5)  # ❌ False, both are same

# Greater than (>)
print(10 > 5)  # ✅ True
print(3 > 8)   # ❌ False

# Less than (<)
print(4 < 6)   # ✅ True
print(7 < 2)   # ❌ False

