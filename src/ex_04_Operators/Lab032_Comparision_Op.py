# 🎯 Objective:
# Understand how to compare two values using comparison operators.
# These operators return either True or False.

# -------------------------------------------------------------
# Step 1: Assign values
x, y = 10, 20

print(f"Given values: x = {x}, y = {y}\n")

# -------------------------------------------------------------
# Step 2: Comparison operations
print("📘 Comparison Results (तुलना के परिणाम):\n")

print(f"1️⃣ Equal to (x == y)   → {x == y}")   # False, because 10 is not equal to 20
print(f"2️⃣ Not equal (x != y)  → {x != y}")   # True, because 10 ≠ 20
print(f"3️⃣ Greater than (x > y) → {x > y}")   # False, 10 is not greater than 20
print(f"4️⃣ Less than (x < y)   → {x < y}")   # True, 10 is less than 20
print(f"5️⃣ Greater or equal (x >= y) → {x >= y}") # False
print(f"6️⃣ Less or equal (x <= y)   → {x <= y}") # True

